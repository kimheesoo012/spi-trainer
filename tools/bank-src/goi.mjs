// g(番号, 難易度, 意味, [正解, よみ, 例文, 韓国語], [[誤答, よみ, 意味, 韓国語] × 3], ポイント, 韓国語の補足)
const Q = '次の意味を表す語として、最も適切なものを選びなさい。';

function g(n, difficulty, meaning, [a, ar, ex, ako], ws, tip, koNote) {
  return {
    id: `goi-${String(n).padStart(3, '0')}`,
    exam: 'SPI',
    test_name: 'SPI3',
    category: '語句の意味',
    difficulty,
    question_ja: `${Q}\n「${meaning}」`,
    choices: [a, ...ws.map((w) => w[0])],
    answer: a,
    explanation_short_ja: `正解は「${a}」(${ar})。意味は「${meaning}」。`,
    explanation_detail_ja: [`${a}(${ar}): ${meaning}。例「${ex}」`, ...ws.map(([w, r, m]) => `${w}(${r}): ${m}`)],
    explanation_ko: [`${a}(${ar}) = ${ako}. 예: ${ex}`, ...ws.map(([w, r, , k]) => `${w}(${r}) = ${k}`), ...(koNote ? [koNote] : [])].join('\n'),
    tip,
    reviewed: true,
  };
}


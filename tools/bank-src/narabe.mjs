const Q = 'ア〜オの文を意味が通るように並べ替えるとき、最も適切な順番を選びなさい。';
const arrow = (s) => s.split('').join('→');

function nb(num, difficulty, S, order, wrongs, lead, detail, ko, tip) {
  return {
    id: `narabe-${String(num).padStart(3, '0')}`,
    exam: 'SPI',
    test_name: 'SPI3',
    category: '文の並べ替え',
    difficulty,
    question_ja: `${Q}\n${['ア', 'イ', 'ウ', 'エ', 'オ'].map((k) => `${k} ${S[k]}`).join('\n')}`,
    choices: [arrow(order), ...wrongs.map(arrow)],
    answer: arrow(order),
    explanation_short_ja: `正しい順番は ${arrow(order)}。\n${lead}`,
    explanation_detail_ja: detail,
    explanation_ko: ko,
    tip,
    reviewed: true,
  };
}

